import { test } from '@e2e-dev/mobile';
import { expect } from 'e2e';
import { signIn } from './shared.ts';

test('profile', async ({ app, device, screen }) => {
  const ctx = { app, device, screen };
  await signIn(ctx, '5550101234', '123456', false);
  await screen.getByTestId('tab-profile').tap();
  await expect(screen.getByTestId('profile-name')).toHaveText('Alex');
  await screen.getByTestId('edit-profile').tap();
  await screen.getByTestId('profile-name-input').fill('Jordan');
  await screen.getByTestId('profile-email-input').fill('jordan');
  await screen.getByTestId('bio-input').tap();
  await expect(screen.getByText('Enter a valid email')).toBeVisible();
  await screen.getByTestId('bio-input').pressSequentially('Runner and coffee lover.');
  await screen.getByTestId('profile-email-input').tap();
  await screen.getByTestId('profile-email-input').pressSequentially('@example.com');
  await device.dismissKeyboard();
  await screen.getByTestId('units-imperial').tap();
  await expect(screen.getByTestId('units-imperial')).toBeChecked();
  await expect(screen.getByTestId('units-metric')).not.toBeChecked();
  await screen.getByTestId('public-profile').tap();
  await expect(screen.getByTestId('public-profile')).toBeChecked();
  await screen.getByTestId('save-profile').tap();
  await expect(screen.getByText('Profile saved')).toBeVisible();
  await expect(screen.getByTestId('profile-name')).toHaveText('Jordan');
  await screen.getByTestId('edit-profile').tap();
  await expect(screen.getByText('Saved: Imperial, public, jordan@example.com')).toBeVisible();
  await screen.getByTestId('header-back').tap();
  await screen.getByTestId('settings').tap();
  await expect(screen.getByTestId('switch-push')).toBeChecked();
  await screen.getByTestId('switch-push').tap();
  await expect(screen.getByTestId('switch-push')).not.toBeChecked();
  await screen.getByTestId('switch-emails').tap();
  await expect(screen.getByTestId('switch-emails')).toBeChecked();
  await screen.getByTestId('clear-cache').tap();
  await screen.getByText(/^(Clear|CLEAR)$/).tap();
  await expect(screen.getByText('Cache cleared')).toBeVisible();
  await screen.scrollUntilVisible(screen.getByTestId('version'), { direction: 'down' });
  await expect(screen.getByText('Version 1.0.0')).toBeVisible();
  await screen.getByTestId('header-back').tap();
  await screen.getByTestId('security').tap();
  // The screen in place before its keys: a tap as it slides in is lost.
  await expect(screen.getByText('Create a PIN')).toBeVisible();
  await new Promise((r) => setTimeout(r, 500));
  const keys = async (s) => { for (const k of s) await screen.getByTestId(k === '<' ? 'key-del' : `key-${k}`).tap(); };
  await keys('1234');
  await expect(screen.getByText('Confirm your PIN')).toBeVisible();
  await keys('1235');
  await expect(screen.getByText("PINs don't match")).toBeVisible();
  await keys('4<1234');
  await expect(screen.getByText('Confirm your PIN')).toBeVisible();
  await keys('1234');
  await expect(screen.getByText('PIN set')).toBeVisible();
  await screen.getByTestId('sign-out').tap();
  await screen.getByText(/^(Yes, sign out|YES, SIGN OUT)$/).tap();
  await expect(screen.getByText("Let's start with your phone number")).toBeVisible();
});
